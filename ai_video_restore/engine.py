ProgressCallback = Callable[[dict[str, object]], None]


@dataclass
class ProcessOptions:
    tile: int = 256
    face_enhance: bool = False
    face_fidelity: float = 0.9
    duration_limit: float | None = None
    output_width: int = 1080
    output_height: int = 1920
    keep_work: bool = False


@dataclass
class StageMetric:
    name: str
    frames: int
    elapsed_seconds: float
    fps: float
    gpu: dict[str, int | str] = field(default_factory=dict)

    def as_dict(self) -> dict[str, object]:
        return {
            "name": self.name,
            "frames": self.frames,
            "elapsed_seconds": round(self.elapsed_seconds, 3),
            "fps": round(self.fps, 3),
            **self.gpu,
        }


def project_root() -> Path:
    return Path(__file__).resolve().parents[1]


def runtime_root() -> Path:
    custom = os.environ.get("AI_VIDEO_RUNTIME")
    return Path(custom).expanduser().resolve() if custom else project_root() / ".runtime"


def data_root() -> Path:
    custom = os.environ.get("AI_VIDEO_DATA")
    if custom:
        root = Path(custom).expanduser().resolve()
    elif os.name == "nt" and os.environ.get("LOCALAPPDATA"):
        root = Path(os.environ["LOCALAPPDATA"]) / "ai-video-restore"
    else:
        root = project_root() / ".data"
    root.mkdir(parents=True, exist_ok=True)
    return root


def find_ncnn() -> Path:
    configured = os.environ.get("REALESRGAN_NCNN")
    candidates = [
        Path(configured) if configured else None,
        runtime_root() / "realesrgan" / ("realesrgan-ncnn-vulkan.exe" if os.name == "nt" else "realesrgan-ncnn-vulkan"),
        Path(shutil.which("realesrgan-ncnn-vulkan") or ""),
    ]
    for candidate in candidates:
        if candidate and candidate.is_file():
            return candidate.resolve()
    raise MediaError("Real-ESRGAN 模型引擎未安装，请重新运行 setup-windows.ps1。")


def find_models(ncnn: Path) -> Path:
    models = ncnn.parent / "models"
    if not models.is_dir():
        raise MediaError(f"Real-ESRGAN 模型目录不存在：{models}")
    return models


def find_codeformer() -> Path:
    configured = os.environ.get("CODEFORMER_ROOT")
    candidate = Path(configured).expanduser() if configured else project_root() / ".deps" / "CodeFormer"
    required = [
        candidate / "inference_codeformer.py",
        candidate / "weights" / "CodeFormer" / "codeformer.pth",
        candidate / "weights" / "facelib" / "detection_mobilenet0.25_Final.pth",
        candidate / "weights" / "facelib" / "parsing_parsenet.pth",
    ]
    if not all(path.is_file() for path in required):
        raise MediaError("CodeFormer 未安装完整，请重新运行 setup-windows.ps1。")
    # CodeFormer's pinned source tree vendors BasicSR but does not commit the
    # generated version module.  Creating the tiny compatibility file here
    # keeps a fresh one-command installation runnable without installing the
    # whole source tree as an editable package.
    basicsr_version = candidate / "basicsr" / "version.py"
    if not basicsr_version.is_file():
        basicsr_version.write_text(
            "# Generated by AI Video Restore for the vendored BasicSR copy.\n"
            "__version__ = '1.4.2'\n"
            "__gitsha__ = 'unknown'\n"
            "version_info = (1, 4, 2)\n",
            encoding="utf-8",
        )
    return candidate.resolve()


def find_face_python() -> Path:
    configured = os.environ.get("AI_VIDEO_PYTHON")
    if configured and Path(configured).is_file():
        return Path(configured).resolve()
    if os.name == "nt":
        candidate = project_root() / ".venv" / "Scripts" / "python.exe"
    else:
        candidate = project_root() / ".venv" / "bin" / "python"
    return candidate.resolve() if candidate.is_file() else Path(sys.executable).resolve()


def sr_backend() -> str:
    try:
        state = json.loads((runtime_root() / "realesrgan-backend.json").read_text(encoding="utf-8"))
        return "cuda" if state.get("backend") == "cuda" else "vulkan"
    except (OSError, ValueError, AttributeError):
        return "vulkan"


def save_sr_backend(backend: str, reason: str = "") -> None:
    root = runtime_root()
    root.mkdir(parents=True, exist_ok=True)
    target = root / "realesrgan-backend.json"
    temporary = target.with_suffix(".tmp")
    temporary.write_text(json.dumps({"backend": backend, "reason": reason}, ensure_ascii=False), encoding="utf-8")
    temporary.replace(target)


def find_cuda_weights() -> Path:
    weights = runtime_root() / "realesrgan" / "RealESRGAN_x4plus.pth"
    if not weights.is_file():
        raise MediaError("CUDA 版 Real-ESRGAN 权重未安装，请重新运行新版安装命令。")
    return weights


def run_sr_stage(
    source_dir: Path, output_dir: Path, expected_frames: int, tile: int,
    callback: ProgressCallback, backend: str | None = None,
) -> tuple[StageMetric, str]:
    selected = backend or sr_backend()
    fallback_reason = ""
    if selected == "vulkan":
        ncnn = find_ncnn()
        command = [str(ncnn), "-i", str(source_dir), "-o", str(output_dir),
                   "-s", "4", "-t", str(tile), "-m", str(find_models(ncnn)),
                   "-g", "0", "-j", "1:2:2", "-f", "png", "-n", "realesrgan-x4plus"]
        try:
            metric = _run_counted_stage(command, output_dir, expected_frames,
                                        "高清增强 · Real-ESRGAN Vulkan", 0.05, 0.67, callback)
            save_sr_backend("vulkan")
            return metric, "vulkan"
        except MediaError as error:
            # Only initialization errors may select another backend. Preserve
            # OOM, broken inputs and partially processed batches as real errors.
            if "vkCreateInstance failed" not in str(error) or _count_frames(output_dir):
                raise
            fallback_reason = str(error)
            callback({"stage": "Vulkan 初始化失败，切换 Real-ESRGAN CUDA", "progress": 0.05,
                      "backend": "cuda", "fallback_reason": fallback_reason})
    codeformer = find_codeformer()
    command = [str(find_face_python()), str(Path(__file__).with_name("cuda_realesrgan.py")),
               "--input", str(source_dir), "--output", str(output_dir), "--tile", str(tile),
               "--weights", str(find_cuda_weights()), "--codeformer", str(codeformer)]
    metric = _run_counted_stage(command, output_dir, expected_frames,
                                "高清增强 · Real-ESRGAN CUDA", 0.05, 0.67, callback,
                                cwd=codeformer)
    save_sr_backend("cuda", fallback_reason)
    return metric, "cuda"


def _run(command: list[str], cwd: Path | None = None) -> subprocess.CompletedProcess[str]:
    process = subprocess.run(
        command,
        cwd=str(cwd) if cwd else None,
        text=True,
        encoding="utf-8",
        errors="replace",
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
    )
    if process.returncode:
        tail = "\n".join(process.stdout.splitlines()[-30:])
        raise MediaError(f"命令执行失败（{process.returncode}）：\n{tail}")
    return process


def _count_frames(folder: Path) -> int:
    return sum(1 for item in folder.glob("*.png") if item.is_file())


def _run_counted_stage(
    command: list[str],
    output_dir: Path,
    expected_frames: int,
    stage_name: str,
    stage_offset: float,
    stage_span: float,
    callback: ProgressCallback,
    cwd: Path | None = None,
    environment: dict[str, str] | None = None,
) -> StageMetric:
    output_dir.mkdir(parents=True, exist_ok=True)
    monitor = GpuMonitor().start()
    started = time.perf_counter()
    process = subprocess.Popen(
        command,
        cwd=str(cwd) if cwd else None,
        env=environment,
        text=True,
        encoding="utf-8",
        errors="replace",
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
    )
    lines: list[str] = []

    def drain() -> None:
        if not process.stdout:
            return
        for line in process.stdout:
            lines.append(line.rstrip())
            if len(lines) > 100:
                del lines[:20]

    reader = threading.Thread(target=drain, daemon=True)
    reader.start()
    last_count = -1
    while process.poll() is None:
        count = min(expected_frames, _count_frames(output_dir))
        if count != last_count:
            elapsed = max(0.001, time.perf_counter() - started)
            fps = count / elapsed
            remaining = (expected_frames - count) / fps if fps > 0 and count >= 2 else None
            callback(
                {
                    "stage": stage_name,
                    "stage_frames": count,
                    "stage_total_frames": expected_frames,
                    "progress": stage_offset + stage_span * (count / max(1, expected_frames)),
                    "stage_fps": fps,
                    "remaining_seconds": remaining,
                }
            )
            last_count = count
        time.sleep(0.35)
    reader.join(timeout=5)
    elapsed = time.perf_counter() - started
    gpu = monitor.stop()
    if process.returncode:
        raise MediaError(f"{stage_name} 失败：\n" + "\n".join(lines[-30:]))
    frames = _count_frames(output_dir)
    if frames != expected_frames:
        raise MediaError(f"{stage_name} 输出帧数异常：期望 {expected_frames}，实际 {frames}。")
    callback(
        {
            "stage": stage_name,
            "stage_frames": frames,
            "stage_total_frames": expected_frames,
            "progress": stage_offset + stage_span,
            "stage_fps": frames / max(elapsed, 0.001),
            "remaining_seconds": 0,
        }
    )
    return StageMetric(stage_name, frames, elapsed, frames / max(elapsed, 0.001), gpu)


def _canvas_filter(width: int, height: int) -> str:
    return (
        "split=2[background][foreground];"
        f"[background]scale={width}:{height}:force_original_aspect_ratio=increase,"
        f"crop={width}:{height},gblur=sigma=34[blurred];"
        f"[foreground]scale={width}:{height}:force_original_aspect_ratio=decrease[fit];"
        "[blurred][fit]overlay=(W-w)/2:(H-h)/2,setsar=1"
    )


def _normalize_sequence(
    ffmpeg: str,
    source_dir: Path,
    output_dir: Path,
    metadata: VideoMetadata,
    options: ProcessOptions,
) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    _run(
        [
            ffmpeg,
            "-hide_banner",
            "-loglevel",
            "error",
            "-y",
            "-framerate",
            f"{metadata.fps.numerator}/{metadata.fps.denominator}",
            "-start_number",
            "1",
            "-i",
            str(source_dir / "%08d.png"),
            "-vf",
            _canvas_filter(options.output_width, options.output_height),
            "-start_number",
            "1",
            str(output_dir / "%08d.png"),
        ]
    )


def _blend_natural(
    ffmpeg: str,
    ai_dir: Path,
    source_dir: Path,
    output_dir: Path,
    metadata: VideoMetadata,
) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    fps = f"{metadata.fps.numerator}/{metadata.fps.denominator}"
    _run(
        [
            ffmpeg,
            "-hide_banner",
            "-loglevel",
            "error",
            "-y",
            "-framerate",
            fps,
            "-start_number",
            "1",
            "-i",
            str(ai_dir / "%08d.png"),
            "-framerate",
            fps,
            "-start_number",
            "1",
            "-i",
            str(source_dir / "%08d.png"),
            "-filter_complex",
            "[0:v][1:v]blend=all_expr='A*0.78+B*0.22'",
            "-start_number",
            "1",
            str(output_dir / "%08d.png"),
        ]
    )


def _validate_ai_alignment(
    ffmpeg: str,
    original_frame: Path,
    ai_frame: Path,
    width: int,
    height: int,
) -> float:
    result = _run(
        [
            ffmpeg,
            "-hide_banner",
            "-i",
            str(original_frame),
            "-i",
            str(ai_frame),
            "-lavfi",
            f"[1:v]scale={width}:{height}[ai];[0:v][ai]ssim",
            "-f",
            "null",
            "-",
        ]
    )
    match = re.search(r"All:([0-9.]+)", result.stdout)
    if not match:
        raise MediaError("无法校验 AI 帧的空间对齐。")
    score = float(match.group(1))
    if score < 0.72:
        raise MediaError(f"AI 输出疑似发生 Tile 拼块错位（SSIM {score:.3f}），已停止生成错误视频。")
    return score


def _encode_video(
    ffmpeg: str,
    frames_dir: Path,
    source: Path,
    output: Path,
    metadata: VideoMetadata,
    frame_count: int,
) -> None:
    assert_safe_output(source, output)
    duration = frame_count / float(metadata.fps)
    partial = output.with_suffix(".partial.mp4")
    command = [
        ffmpeg,
        "-hide_banner",
        "-loglevel",
        "error",
        "-y",
        "-framerate",
        f"{metadata.fps.numerator}/{metadata.fps.denominator}",
        "-start_number",
        "1",
        "-i",
        str(frames_dir / "%08d.png"),
        "-i",
        str(source),
        "-map",
        "0:v:0",
    ]
    if metadata.has_audio:
        command.extend(["-map", "1:a:0?", "-c:a", "aac", "-b:a", "192k", "-ar", "48000", "-af", "aresample=async=1:first_pts=0"])
    command.extend(
        [
            "-c:v",
            "libx264",
            "-preset",
            "medium",
            "-crf",
            "17",
            "-profile:v",
            "high",
            "-pix_fmt",
            "yuv420p",
            "-movflags",
            "+faststart",
            "-t",
            f"{duration:.9f}",
            str(partial),
        ]
    )
    _run(command)
    partial.replace(output)


def _comparison(ffmpeg: str, images: list[tuple[str, Path]], output: Path) -> None:
    command = [ffmpeg, "-hide_banner", "-loglevel", "error", "-y"]
    for _, image in images:
        command.extend(["-i", str(image)])
    filters: list[str] = []
    labels: list[str] = []
    for index, (label, _) in enumerate(images):
        name = f"v{index}"
        filters.append(
            f"[{index}:v]scale=540:960:force_original_aspect_ratio=decrease,"
            f"pad=540:960:(ow-iw)/2:(oh-ih)/2:color=black,"
            f"drawbox=x=0:y=0:w=iw:h=64:color=black@0.70:t=fill,"
            f"drawtext=text='{label}':x=24:y=17:fontsize=27:fontcolor=white[{name}]"
        )
        labels.append(f"[{name}]")
    filters.append("".join(labels) + f"hstack=inputs={len(images)}[out]")
    command.extend(["-filter_complex", ";".join(filters), "-map", "[out]", "-frames:v", "1", "-q:v", "2", str(output)])
    try:
        _run(command)
    except MediaError:
        fallback = [ffmpeg, "-hide_banner", "-loglevel", "error", "-y"]
        for _, image in images:
            fallback.extend(["-i", str(image)])
        raw_filters = [
            f"[{index}:v]scale=540:960:force_original_aspect_ratio=decrease,pad=540:960:(ow-iw)/2:(oh-ih)/2:color=black[v{index}]"
            for index in range(len(images))
        ]
        raw_filters.append("".join(f"[v{i}]" for i in range(len(images))) + f"hstack=inputs={len(images)}[out]")
        fallback.extend(["-filter_complex", ";".join(raw_filters), "-map", "[out]", "-frames:v", "1", "-q:v", "2", str(output)])
        _run(fallback)


def _validate_output(path: Path, source_meta: VideoMetadata, expected_duration: float, ffprobe: str) -> dict[str, object]:
    output_meta = probe_video(path, ffprobe=ffprobe)
    tolerance = max(0.08, 1 / float(source_meta.fps) + 0.03)
    duration_delta = abs(output_meta.duration - expected_duration)
    if output_meta.width != 1080 or output_meta.height != 1920:
        raise MediaError(f"输出分辨率错误：{path.name} 为 {output_meta.width}×{output_meta.height}。")
    if output_meta.video_codec != "h264":
        raise MediaError(f"输出编码错误：{path.name} 不是 H.264。")
    if duration_delta > tolerance:
        raise MediaError(f"输出时长偏差过大：{path.name} 偏差 {duration_delta:.3f} 秒。")
    if source_meta.has_audio and not output_meta.has_audio:
        raise MediaError(f"输出缺少音频：{path.name}")
    return {"path": str(path), "duration": output_meta.duration, "duration_delta": duration_delta, "fps": float(output_meta.fps)}


def process_video(source: str | Path, options: ProcessOptions, callback: ProgressCallback | None = None) -> dict[str, object]:
    notify = callback or (lambda _: None)
    started_wall = time.time()
    source_path = Path(source).expanduser().resolve()
    ffmpeg = shutil.which("ffmpeg")
    ffprobe = shutil.which("ffprobe")
    if not ffmpeg or not ffprobe:
        raise MediaError("缺少 FFmpeg/FFprobe，请重新运行安装脚本。")
    metadata = probe_video(source_path, ffprobe=ffprobe)
    duration = min(metadata.duration, options.duration_limit) if options.duration_limit else metadata.duration
    expected_frames = max(1, round(duration * float(metadata.fps)))

    job_id = uuid.uuid4().hex[:12]
    work = data_root() / "work" / f"{source_path.stem}-{job_id}"
    original = work / "original"
    hd_raw = work / "hd-x4"
    source_frames = work / "source-1080"
    natural_frames = work / "natural-1080"
    hd_frames = work / "hd-1080"
    face_frames = work / "face-1080"
    for folder in (original, hd_raw, source_frames, natural_frames, hd_frames):
        folder.mkdir(parents=True, exist_ok=True)

    metrics: list[StageMetric] = []
    output_paths: dict[str, Path] = {
        "natural": prefixed_output(source_path, "自然"),
        "hd": prefixed_output(source_path, "高清"),
        "comparison": prefixed_output(source_path, "对比", ".jpg"),
    }
    if options.face_enhance:
        output_paths["face"] = prefixed_output(source_path, "人脸")

    try:
        notify({"stage": "解析视频", "progress": 0.01, "metadata": metadata.as_dict()})
        extract = [
            ffmpeg,
            "-hide_banner",
            "-loglevel",
            "error",
            "-y",
            "-i",
            str(source_path),
            "-map",
            "0:v:0",
            "-t",
            f"{duration:.9f}",
            "-vf",
            f"fps={metadata.fps.numerator}/{metadata.fps.denominator}",
            "-start_number",
            "1",
            str(original / "%08d.png"),
        ]
        _run(extract)
        actual_frames = _count_frames(original)
        if not actual_frames:
            raise MediaError("FFmpeg 没有解码出任何视频帧。")
        expected_frames = actual_frames
        notify({"stage": "视频已解码", "progress": 0.05, "stage_frames": actual_frames, "stage_total_frames": actual_frames})

        # The x4plus NCNN model must run at its native x4 scale when tiled.
        # Requesting -s 2 with this model corrupts tile placement in the official
        # 20220424 Windows binary, so the final target resize happens in FFmpeg.
        model_scale = 4
        metric, backend = run_sr_stage(original, hd_raw, actual_frames, options.tile, notify)
        metrics.append(metric)
        middle = max(1, actual_frames // 2)
        alignment_ssim = _validate_ai_alignment(
            ffmpeg,
            original / f"{middle:08d}.png",
            hd_raw / f"{middle:08d}.png",
            metadata.width,
            metadata.height,
        )

        notify({"stage": "生成自然保真版", "progress": 0.73})
        _normalize_sequence(ffmpeg, original, source_frames, metadata, options)
        _normalize_sequence(ffmpeg, hd_raw, hd_frames, metadata, options)
        _blend_natural(ffmpeg, hd_frames, source_frames, natural_frames, metadata)

        if options.face_enhance:
            codeformer = find_codeformer()
            face_result = work / "codeformer"
            face_frames = face_result / "final_results"
            environment = os.environ.copy()
            environment["TORCH_FORCE_NO_WEIGHTS_ONLY_LOAD"] = "1"
            command = [
                str(find_face_python()),
                str(codeformer / "inference_codeformer.py"),
                "-i",
                str(hd_frames),
                "-o",
                str(face_result),
                "-w",
                f"{options.face_fidelity:.2f}",
                "-s",
                "1",
                "--detection_model",
                "retinaface_mobile0.25",
            ]
            metrics.append(
                _run_counted_stage(
                    command,
                    face_frames,
                    actual_frames,
                    "人脸增强 · CodeFormer",
                    0.78,
                    0.12,
                    notify,
                    cwd=codeformer,
                    environment=environment,
                )
            )

        notify({"stage": "编码与音频同步", "progress": 0.91})
        _encode_video(ffmpeg, natural_frames, source_path, output_paths["natural"], metadata, actual_frames)
        notify({"stage": "编码高清版", "progress": 0.94})
        _encode_video(ffmpeg, hd_frames, source_path, output_paths["hd"], metadata, actual_frames)
        if options.face_enhance:
            notify({"stage": "编码人脸版", "progress": 0.96})
            _encode_video(ffmpeg, face_frames, source_path, output_paths["face"], metadata, actual_frames)

        comparison_images = [
            ("NATURAL", natural_frames / f"{middle:08d}.png"),
            ("HD", hd_frames / f"{middle:08d}.png"),
        ]
        if options.face_enhance:
            comparison_images.append(("FACE", face_frames / f"{middle:08d}.png"))
        _comparison(ffmpeg, comparison_images, output_paths["comparison"])

        notify({"stage": "校验输出", "progress": 0.98})
        expected_duration = actual_frames / float(metadata.fps)
        validation = {
            name: _validate_output(path, metadata, expected_duration, ffprobe)
            for name, path in output_paths.items()
            if path.suffix.lower() == ".mp4"
        }
        report = {
            "source": metadata.as_dict(),
            "test_duration_limit": options.duration_limit,
            "processed_frames": actual_frames,
            "processed_duration": expected_duration,
            "tile": options.tile,
            "realesrgan_output_scale": model_scale,
            "realesrgan_backend": backend,
            "natural_ai_mix": 0.78,
            "ai_alignment_ssim": round(alignment_ssim, 6),
            "face_enhance": options.face_enhance,
            "outputs": {name: str(path) for name, path in output_paths.items()},
            "metrics": [metric.as_dict() for metric in metrics],
            "validation": validation,
            "total_elapsed_seconds": round(time.time() - started_wall, 3),
            "completed_at": time.strftime("%Y-%m-%d %H:%M:%S"),
        }
        report_path = prefixed_output(source_path, "报告", ".json")
        report_path.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
        report["report_path"] = str(report_path)
        notify({"stage": "完成", "progress": 1.0, "remaining_seconds": 0, "outputs": report["outputs"]})
        return report
    finally:
        if work.exists() and not options.keep_work:
            shutil.rmtree(work, ignore_errors=True)


def process_face_version(
    source: str | Path,
    options: ProcessOptions,
    callback: ProgressCallback | None = None,
) -> dict[str, object]:
    """Create only the CodeFormer version from an existing HD result."""
    notify = callback or (lambda _: None)
    started_wall = time.time()
    source_path = Path(source).expanduser().resolve()
    hd_video = prefixed_output(source_path, "高清")
    natural_video = prefixed_output(source_path, "自然")
    if not hd_video.is_file() or not natural_video.is_file():
        raise MediaError("追加人脸增强前，需要先生成同目录下的自然版和高清版。")

    ffmpeg = shutil.which("ffmpeg")
    ffprobe = shutil.which("ffprobe")
    if not ffmpeg or not ffprobe:
        raise MediaError("缺少 FFmpeg/FFprobe，请重新运行安装脚本。")
    metadata = probe_video(source_path, ffprobe=ffprobe)
    duration = min(metadata.duration, options.duration_limit) if options.duration_limit else metadata.duration
    job_id = uuid.uuid4().hex[:12]
    work = data_root() / "work" / f"{source_path.stem}-face-{job_id}"
    hd_frames = work / "hd-1080"
    face_result = work / "codeformer"
    face_frames = face_result / "final_results"
    hd_frames.mkdir(parents=True, exist_ok=True)
    face_output = prefixed_output(source_path, "人脸")
    comparison_output = prefixed_output(source_path, "对比", ".jpg")

    try:
        notify({"stage": "提取高清帧", "progress": 0.03})
        _run(
            [
                ffmpeg,
                "-hide_banner",
                "-loglevel",
                "error",
                "-y",
                "-i",
                str(hd_video),
                "-t",
                f"{duration:.9f}",
                "-vf",
                f"fps={metadata.fps.numerator}/{metadata.fps.denominator}",
                "-start_number",
                "1",
                str(hd_frames / "%08d.png"),
            ]
        )
        actual_frames = _count_frames(hd_frames)
        if not actual_frames:
            raise MediaError("高清版没有解码出任何视频帧。")

        codeformer = find_codeformer()
        environment = os.environ.copy()
        environment["TORCH_FORCE_NO_WEIGHTS_ONLY_LOAD"] = "1"
        metric = _run_counted_stage(
            [
                str(find_face_python()),
                str(codeformer / "inference_codeformer.py"),
                "-i",
                str(hd_frames),
                "-o",
                str(face_result),
                "-w",
                f"{options.face_fidelity:.2f}",
                "-s",
                "1",
                "--detection_model",
                "retinaface_mobile0.25",
            ],
            face_frames,
            actual_frames,
            "人脸增强 · CodeFormer",
            0.08,
            0.78,
            notify,
            cwd=codeformer,
            environment=environment,
        )

        notify({"stage": "编码人脸版", "progress": 0.88})
        _encode_video(ffmpeg, face_frames, source_path, face_output, metadata, actual_frames)
        middle = max(1, actual_frames // 2)
        natural_middle = work / "natural-middle.png"
        _run(
            [
                ffmpeg,
                "-hide_banner",
                "-loglevel",
                "error",
                "-y",
                "-ss",
                f"{middle / float(metadata.fps):.6f}",
                "-i",
                str(natural_video),
                "-frames:v",
                "1",
                str(natural_middle),
            ]
        )
        _comparison(
            ffmpeg,
            [
                ("NATURAL", natural_middle),
                ("HD", hd_frames / f"{middle:08d}.png"),
                ("FACE", face_frames / f"{middle:08d}.png"),
            ],
            comparison_output,
        )
        expected_duration = actual_frames / float(metadata.fps)
        validation = _validate_output(face_output, metadata, expected_duration, ffprobe)
        report = {
            "source": metadata.as_dict(),
            "test_duration_limit": options.duration_limit,
            "processed_frames": actual_frames,
            "processed_duration": expected_duration,
            "face_fidelity": options.face_fidelity,
            "outputs": {"face": str(face_output), "comparison": str(comparison_output)},
            "metrics": [metric.as_dict()],
            "validation": {"face": validation},
            "total_elapsed_seconds": round(time.time() - started_wall, 3),
            "completed_at": time.strftime("%Y-%m-%d %H:%M:%S"),
        }
        report_path = prefixed_output(source_path, "人脸报告", ".json")
        report_path.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
        report["report_path"] = str(report_path)
        notify({"stage": "完成", "progress": 1.0, "remaining_seconds": 0, "outputs": report["outputs"]})
        return report
    finally:
        if work.exists() and not options.keep_work:
            shutil.rmtree(work, ignore_errors=True)

